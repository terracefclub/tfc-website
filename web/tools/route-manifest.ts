// Route manifest: the routes the SvelteKit app serves, derived from `src/routes` so a new route can never be shadowed
// by an imported redirect or produce a dead redirect row. The manifest is generated and checked in; CI (`bun test`) fails
// when it no longer matches the route tree, and the importer refuses to plan against a stale one.
//   bun web/tools/route-manifest.ts          regenerate web/src/lib/route-manifest.ts and cms/src/lib/route-manifest.ts
//   bun web/tools/route-manifest.ts --check  exit 1 when either file is stale
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { explicitReservedPrefixes } from '../src/lib/site-routes-explicit';

const here = new URL('.', import.meta.url).pathname;
export const routesDir = resolve(here, '../src/routes');
export const manifestFiles = [resolve(here, '../src/lib/route-manifest.ts'), resolve(here, '../../cms/src/lib/route-manifest.ts')];

export type RouteManifest = { exact: string[]; prefixes: string[] };
const routeFile = /^\+(?:page|server)(?:[.@].*)?$/;

/**
 * Walk a SvelteKit routes directory. A directory with a `+page*` or `+server*` file is a route. A route made only of static
 * segments is an exact route; a route containing a dynamic segment (`[slug]`, `[...rest]`) reserves everything below its static
 * part. Route groups `(name)` do not appear in the URL. Pure and deterministic.
 */
export function scanRoutes(dir: string): RouteManifest {
  const exact = new Set<string>(), prefixes = new Set<string>();
  const walk = (current: string, segments: string[]) => {
    const entries = readdirSync(current, { withFileTypes: true });
    if (entries.some(entry => entry.isFile() && routeFile.test(entry.name))) {
      const dynamic = segments.findIndex(segment => /^\[/.test(segment));
      if (dynamic === -1) exact.add('/' + segments.join('/'));
      else {
        const base = '/' + segments.slice(0, dynamic).join('/');
        if (base === '/') throw new Error('A top-level dynamic route would reserve every path; reserve it explicitly instead.');
        prefixes.add(base);
      }
    }
    for (const entry of entries) {
      if (!entry.isDirectory()) continue;
      walk(join(current, entry.name), /^\(.*\)$/.test(entry.name) ? segments : [...segments, entry.name]);
    }
  };
  walk(dir, []);
  return { exact: [...exact].sort(), prefixes: [...prefixes].sort() };
}

/** The shipped manifest: derived routes plus the explicit prefixes that are reserved without being app routes (`/api`, `/admin`, ...). */
export function buildManifest(dir = routesDir): RouteManifest {
  const derived = scanRoutes(dir);
  return { exact: derived.exact, prefixes: [...new Set([...derived.prefixes, ...explicitReservedPrefixes])].sort() };
}

export function manifestSource(manifest: RouteManifest): string {
  const list = (items: string[]) => items.map(item => `'${item}'`).join(', ');
  return `// GENERATED by web/tools/route-manifest.ts from web/src/routes. Do not edit: run \`bun web/tools/route-manifest.ts\`.
// CI fails when this file no longer matches the route tree.
/** Static routes the app serves (case-insensitive match on the exact path). */
export const appExactRoutes: readonly string[] = [${list(manifest.exact)}];
/** Route prefixes: the path itself and everything below it belongs to the app or is reserved. */
export const appRoutePrefixes: readonly string[] = [${list(manifest.prefixes)}];
`;
}

export function staleManifests(dir = routesDir): string[] {
  const wanted = manifestSource(buildManifest(dir));
  return manifestFiles.filter(file => !existsSync(file) || readFileSync(file, 'utf8') !== wanted);
}

if (import.meta.main) {
  if (process.argv.includes('--check')) {
    const stale = staleManifests();
    if (stale.length) { console.error('The route manifest is stale. Run: bun web/tools/route-manifest.ts'); process.exit(1); }
  } else {
    const source = manifestSource(buildManifest());
    for (const file of manifestFiles) writeFileSync(file, source);
    console.log('Route manifest written.');
  }
}
